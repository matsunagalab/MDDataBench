def finalize(items, report):
    """dataset.json entries for the test split, and the non-polymer audit rows."""
    import csv
    meta_path = DATASET / "dataset.json"
    meta = json.loads(meta_path.read_text())
    known = {t["task_id"] for t in meta["tasks"]}
    for item in items:
        if item["task_id"] in known:
            continue
        meta["tasks"].append({"task_id": item["task_id"], "split": "test", "axis": item["axis"],
                              "path": f"tasks/{item['task_id']}/task.json",
                              "prompt": f"tasks/{item['task_id']}/prompt.md"})
    splits = collections.Counter(t["split"] for t in meta["tasks"])
    meta["counts"] = {"total": len(meta["tasks"]), "train": splits["train"],
                      "eval": splits["eval"], "test": splits["test"]}
    if meta.get("dataset_id") != DATASET_ID:
        meta["dataset_id"] = DATASET_ID
        meta.setdefault("changelog", []).append(CHANGELOG)
    if "test split" not in meta["description"]:
        meta["description"] += (" Version 0.6 adds a held-out test split of 30 new systems, "
                                "sequence-distinct from the 98 and from everything MDClaw was "
                                "developed against.")
    meta_path.write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n")

    # One audit row per test task, in the columns of the 2026-09-14 audit, so the
    # v0.4 script can be rerun over the whole dataset and shown to change nothing.
    rows = list(csv.DictReader(AUDIT_CSV.open()))
    fields = list(rows[0].keys())
    have = {r["task"] for r in rows}
    by_id = {t["task_id"]: t for t in report["tasks"]}
    for item in items:
        if item["task_id"] in have:
            continue
        built = by_id[item["task_id"]]
        task = json.loads((DATASET / "tasks" / item["task_id"] / "task.json").read_text())
        excluded = task["reference"]["selection"].get("excluded_components") or []
        rows.append({
            "task": item["task_id"], "pdb": item["pdb_id"], "chains": "".join(built["chains"]),
            "deposit_nonpoly": " ".join(f"{k}x{v}" for k, v in sorted(built["hetero_selected"].items())),
            "deposit_other_chains": "", "glycan": "",
            "in_reference": " ".join(built["in_reference"]),
            "ref_nonstd": " ".join(f"{k}x{v}" for k, v in sorted(built["reference_nonpolymer"].items())),
            "prompt_mentions": " ".join(x["name"] for x in built["ligands"]),
            "prompt_exclusion_wording": "yes" if excluded else "",
            "unaddressed": " ".join(excluded),
            "flag": "ok-excl" if excluded else "ok",
        })
    with AUDIT_CSV.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    return {"dataset_id": meta["dataset_id"], "counts": meta["counts"], "audit_rows": len(rows)}


def regenerate_cast():
    """Derive every shipped prompt again and compare it with the shipped text."""
    rows = []
    for path in sorted((DATASET / "tasks").glob("*/task.json")):
        task = json.loads(path.read_text())
        if task["split"] == "test":
            continue
        ref = task["reference"]
        try:
            d = derive(task["task_id"], ref["node"], ref["accession"], ref["pdb_ids"][0])
            sel = ref["selection"]
            # The cast's own decisions where the derivation has no source of its
            # own: which twin chain (029, 034, 062, 080), the stated disulfides,
            # the kept zinc, and the extra component of 042.
            if sorted(sel["chains"]) != sorted(d["chains"]):
                rows.append({"task": task["task_id"], "status": "chains_differ",
                             "shipped": sel["chains"], "derived": d["chains"]})
                continue
            derived_excluded = d["excluded"]
            d["excluded"] = sel.get("excluded_components") or []
            text = prompt_for(task["task_id"], ref["pdb_ids"][0], d, ref["production_window_ns"],
                              disulfides=sel.get("stated_disulfides"),
                              kept=sel.get("kept_components") or ())
            shipped = (path.parent / "prompt.md").read_text()

            def body(prompt):
                return re.sub(r"^Simulate .*?, PDB entry ", "Simulate <name>, PDB entry ",
                              prompt, count=1, flags=re.M)
            status = ("identical" if text == shipped else
                      "identical_but_molecule_name" if body(text) == body(shipped) else "differs")
            rows.append({"task": task["task_id"], "status": status,
                         "derived": text if text != shipped else None,
                         "excluded_derived": derived_excluded,
                         "excluded_shipped": sel.get("excluded_components") or [],
                         "ligands": d["ligands"]})
        except BaseException as exc:                                # noqa: BLE001
            rows.append({"task": task["task_id"], "status": "error",
                         "error": f"{type(exc).__name__}: {exc}"})
    summary = collections.Counter(r["status"] for r in rows)
    return {"summary": dict(summary), "rows": rows}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("command", choices=["plan", "fetch", "calibrate", "build", "regenerate",
                                            "finalize"])
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--only", default="", help="comma-separated task ids")
    parser.add_argument("--draft", default="", help="write drafts (no calibration) here")
    parser.add_argument("--extra", default="", help="also build these PDB ids from selected.json")
    args = parser.parse_args(argv)
    items, replaced = plan()
    if args.extra:
        data = json.loads((WORKDIR / "selection" / "selected.json").read_text())
        for s_ in data["selected"] + data["reserves"]:
            if s_["pdb_id"] in args.extra.split(","):
                axis = s_["category"]
                items.append(dict(s_, axis=axis,
                                  task_id=f"999_{DIR_AXIS.get(axis, axis)}_{s_['pdb_id'].lower()}"))
    if args.only:
        wanted = set(args.only.split(","))
        items = [i for i in items if i["task_id"] in wanted]
    if args.command == "plan":
        print(json.dumps({"tasks": [(i["task_id"], i["node"], i["accession"]) for i in items],
                          "replaced": replaced}, indent=1))
    elif args.command == "fetch":
        for item in items:
            print(item["task_id"], fetch(item), flush=True)
    elif args.command == "calibrate":
        def one(item):
            t0 = time.time()
            bundle = BUNDLE_ROOT / f"{item['node']}_{item['accession']}"
            block = calibration_for(item["node"], item["accession"], bundle)
            return item["task_id"], block["windows"], round(time.time() - t0)
        with cf.ThreadPoolExecutor(max_workers=args.workers) as pool:
            for result in pool.map(one, items):
                print(*result, flush=True)
    elif args.command == "build":
        _, _, sample = cast_texts()
        report = {"replaced": replaced,
                  "tasks": [build_task(i, sample, args.draft or None) for i in items]}
        name = "draft_report.json" if args.draft else "build_report.json"
        (WORKDIR / "build").mkdir(parents=True, exist_ok=True)
        (WORKDIR / "build" / name).write_text(json.dumps(report, indent=1))
        print(json.dumps(report, indent=1)[:4000])
    elif args.command == "finalize":
        report = json.loads((WORKDIR / "build" / "build_report.json").read_text())
        print(json.dumps(finalize(items, report), indent=1))
    elif args.command == "regenerate":
        result = regenerate_cast()
        (WORKDIR / "build").mkdir(parents=True, exist_ok=True)
        (WORKDIR / "build" / "regenerate_cast.json").write_text(json.dumps(result, indent=1))
        print(json.dumps(result["summary"]))
        for row in result["rows"]:
            if row["status"] != "identical":
                print(row["task"], row["status"], row.get("error", ""), row.get("shipped", ""),
                      row.get("derived", "") if row["status"] == "chains_differ" else "")


if __name__ == "__main__":
    main()
