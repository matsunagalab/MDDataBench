def formula_counts(text):
    out = collections.Counter()
    for symbol, number in re.findall(r"([A-Z][a-z]?)(\d*)", text or ""):
        out[symbol.upper()] += int(number or 1)
    return out


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


# --- deposit / reference readers --------------------------------------------


def hetero_residues(deposit: Path):
    """Non-polymer residues of a deposit: (chain, number, name, elements)."""
    modres = set(tb.modres_parents(str(deposit)))
    out = collections.OrderedDict()
    for line in open(deposit, errors="replace"):
        if line.startswith("ENDMDL"):
            break
        if not line.startswith("HETATM"):
            continue
        name = line[17:20].strip()
        if name in WATER or name in modres or name in CAPS:
            continue
        key = (line[21], line[22:27].strip(), name)
        element = (line[76:78].strip() or line[12:16].strip()[:1]).upper()
        out.setdefault(key, collections.Counter())[element] += 1
    return out


def hetero_residues_cif(cif: Path):
    """The same, read from the mmCIF the contract audit reads.

    The two formats can disagree on a component's name: RCSB's PDB-format 1C52
    calls its haem HEC, its mmCIF HEM, and the cast (and the audit) follow the
    mmCIF.
    """
    import gemmi
    structure = gemmi.read_structure(str(cif))
    structure.setup_entities()
    out = collections.OrderedDict()
    for chain in structure[0]:
        for residue in chain:
            if residue.het_flag != "H" or residue.is_water():
                continue
            # A free amino acid is a ligand (6MJ7's arginine); only a residue
            # of a polymer entity is part of the chain.
            if residue.name in CAPS or residue.entity_type == gemmi.EntityType.Polymer:
                continue
            key = (chain.name, str(residue.seqid.num) + (residue.seqid.icode.strip()),
                   residue.name)
            counts = collections.Counter(atom.element.name.upper() for atom in residue)
            out[key] = counts
    return out


def reference_components(reference: Path):
    """Non-polymer residues kept in the reference: name -> list of element counters."""
    out = collections.defaultdict(list)
    current, counts = None, None
    for line in open(reference, errors="replace"):
        if not line.startswith(("ATOM", "HETATM")):
            continue
        name = line[17:21].strip()
        if (name.upper() in cp.SOLVENT_RESIDUES - {"ZN", "CA", "MG"}
                or name.upper() in cp.LIPID_RESIDUES or name in tb.AMINO
                or name in tb.NUCLEIC or name in cp.CANONICAL_RESIDUE
                or name in vc.CHARMM_NUCLEIC):
            continue
        key = (line[21], line[22:27].strip(), name)
        element = (line[76:78].strip() or line[12:16].strip()[:1]).upper()
        if key != current:
            current, counts = key, collections.Counter()
            out[name].append(counts)
        counts[element] += 1
    return out


def heavy(counter):
    return collections.Counter({k: v for k, v in counter.items() if k not in ("H", "D")})


# --- selection ---------------------------------------------------------------


def pre_merge_entries(record, deposit):
    """``selection()`` up to, not including, the per-deposit-chain merge.

    One entry per reference polymer, which is what ``effective_components``
    records: the pieces the reference holds as one backbone.
    """
    original = tb.merge_by_deposit_chain
    try:
        tb.merge_by_deposit_chain = lambda entries: entries
        return tb.selection(record, str(deposit))
    finally:
        tb.merge_by_deposit_chain = original


def name_hint(entries, deposit, metadata):
    """Move a single-chain selection to the chain the depositor named, if it is a twin."""
    if len(entries) != 1:
        return entries
    named = tb.chain_from_name(metadata.get("NAME"))
    entry = entries[0]
    chain = tb.resolve_chain(named, entry["deposit_chain"], str(deposit))
    if chain == entry["deposit_chain"]:
        return entries
    full = tb.seqres(str(deposit))
    if full.get(chain) != full.get(entry["deposit_chain"]):
        return entries
    return [tb.remeasure_on(entry, str(deposit), chain)]


def derive(task_id, node, accession, pdb, workdir=WORKDIR, bundle=None):
    """Everything the contract and the prompt need, derived from the three sources."""
    meta = project(node, accession).get("metadata") or {}
    bundle = Path(bundle or BUNDLE_ROOT / f"{node}_{accession}")
    reference = bundle / "reference.pdb"
    deposit = vc.deposit_pdb(workdir, pdb)
    record, polymers = vc.build_record(reference, deposit)
    chosen = tb.selection(record, str(deposit))
    chosen = name_hint(chosen, deposit, meta)
    pre = pre_merge_entries(record, deposit)
    if len(chosen) == 1 and len(pre) >= 1 and chosen[0]["deposit_chain"] != pre[0]["deposit_chain"]:
        pre = [tb.remeasure_on(e, str(deposit), chosen[0]["deposit_chain"])
               if e.get("seqres_spans") else dict(e, deposit_chain=chosen[0]["deposit_chain"])
               for e in pre]
    chains = [e["deposit_chain"] for e in chosen]
    entry = rcsb_entry(pdb)

    # Modified residues the reference reverted, on the simulated ranges only.
    def inside(chain, number):
        for e in chosen:
            if e["deposit_chain"] != chain:
                continue
            for lo, hi in e["ranges"]:
                try:
                    if int(lo) <= int(number) <= int(hi):
                        return True
                except (TypeError, ValueError):
                    if str(number) in (str(lo), str(hi)):
                        return True
        return False
    modres = [m for m in tb.modified_residues(str(deposit), set(chains))
              if inside(m["chain"], m["residue"])]
    # One entry per reference polymer, because stated_protonation indexes its
    # entries by reference monomer (a merged chain loses the second piece's HIP).
    protonation = tb.stated_protonation(str(reference), str(deposit), pre)

    # Non-polymer components: what the deposit carries on the selected chains,
    # and which of them the reference keeps.
    cif = DATASET / "_deposits" / f"{pdb.upper()}.cif"
    hetero = hetero_residues_cif(cif) if cif.exists() else hetero_residues(deposit)
    selected = collections.Counter()
    for (chain, number, name), elements in hetero.items():
        if chain in chains:
            selected[name] += 1
    kept_ref = reference_components(reference)
    ligands, in_reference, metals = [], set(), []
    for name, instances in kept_ref.items():
        upper = name.upper()
        if upper in METAL_NAMES or upper in getattr(cp, "METAL_RESIDUES", set()):
            if upper in selected:
                in_reference.add(upper)
            continue
        if upper in CAPS:
            continue
        for counts in instances:
            # The deposit component with the same heavy-atom formula is the one
            # the reference carries (ligate names it LIG).
            matches = sorted({hname for (chain, _, hname), elements in hetero.items()
                              if chain in chains and heavy(elements) == heavy(counts)})
            if not matches:
                # A ligand the deposit models only in part (1G74's OLA) still has
                # the full formula in the CCD.
                matches = sorted({hname for (chain, _, hname) in hetero
                                  if chain in chains and heavy(formula_counts(
                                      (chem_comp(hname).get("chem_comp") or {}).get("formula")))
                                  == heavy(counts)})
            if len(matches) != 1:
                raise SystemExit(f"{task_id}: reference {name} matches deposit components "
                                 f"{matches or 'none'} by heavy-atom formula")
            code = matches[0]
            ccd = chem_comp(code).get("chem_comp") or {}
            ccd_h = formula_counts(ccd.get("formula")).get("H", 0)
            charge = int(ccd.get("pdbx_formal_charge") or 0) + (counts.get("H", 0) - ccd_h)
            ligands.append({"name": code, "charge": charge, "reference_name": name,
                            "reference_atoms": sum(counts.values()),
                            "ccd_formula": ccd.get("formula"),
                            "ccd_formal_charge": ccd.get("pdbx_formal_charge")})
            in_reference.add(code)
    # Glycans on glycosylation sites are covered by the glycosylation sentence.
    glycan_sites = any("GLYCOSYLATION" in str(m.get("note", "")).upper() for m in modres)
    excluded = sorted(n for n in selected if n not in in_reference
                      and not (glycan_sites and n in SUGARS))
    # Terminal caps the deposit carries and the reference does not are named in
    # the same sentence; the cast's 1DFJ left its ACE unsaid and is the one
    # contract the audit reports a cap mismatch for.
    deposit_caps = sorted({name for line in open(deposit, errors="replace")
                           if line.startswith(("ATOM", "HETATM"))
                           and (name := line[17:20].strip()) in CAPS})
    reference_caps = {name for name in kept_ref if name.upper() in CAPS}
    if deposit_caps and not reference_caps:
        excluded = sorted(set(excluded) | set(deposit_caps))
    # Structural metals: the ions the reference keeps bound to its polymer.
    for site in vc.metals_in_reference(reference):
        if site["bound"]:
            metals.append(re.sub(r"[-0-9]+$", "", site["metal"]).upper())
    metal_words = sorted({METAL_NAMES.get(m, m.lower()) for m in metals})

    # Effective components: one per reference backbone, needed whenever a chain
    # carries more than one range or an omitted span.
    multi = any(len(e["ranges"]) > 1 or e.get("omitted") for e in chosen)
    effective = []
    if multi:
        for e in pre:
            pieces = []
            for lo, hi in e["ranges"]:
                pieces.append([str(lo), str(hi)])
            effective.append({"deposit_chain": e["deposit_chain"], "ranges": pieces})

    system = meta
    nucleic = bool(system.get("DNARES") or system.get("RNARES"))
    protein = bool(system.get("PROTRES"))
    subject = "system" if (protein and nucleic) else ("nucleic acid" if nucleic else "protein")
    # The builder's own naming: the polymer entities on the selected deposit
    # chains (first two), else the deposit title.  The cast's multi-entity inr
    # prompts carry the deposit title instead, from generator inputs that were
    # never committed; the name is not part of any check.
    title = tb.molecule_name(entry, chains)
    return {"meta": meta, "bundle": bundle, "reference": reference, "deposit": deposit,
            "record": record, "polymers": polymers, "chosen": chosen, "pre": pre,
            "chains": chains, "entry": entry, "modres": modres, "protonation": protonation,
            "ligands": ligands, "excluded": excluded, "metals": metal_words,
            "effective": effective, "subject": subject, "title": title,
            "hetero_selected": dict(selected), "in_reference": sorted(in_reference),
            "reference_nonpolymer": {k: len(v) for k, v in kept_ref.items()}}


def prompt_for(task_id, pdb, d, window_ns, disulfides=None, kept=()):
    meta = dict(d["meta"])
    meta["_pressure_bar"] = 1
    if d["metals"]:
        meta["_structural_metals"] = d["metals"]
    return tb.build_prompt(
        task_id, d["title"], pdb, meta, d["chosen"], d["modres"], d["protonation"],
        window_ns, disulfides=disulfides, excluded_components=d["excluded"],
        effective_components=d["effective"], kept_components=kept,
        polymer_subject=d["subject"], ligands=d["ligands"])


def selection_block(d, disulfides=None, kept=()):
    chosen = d["chosen"]
    ranges = {e["deposit_chain"]: [[str(a), str(b)] for a, b in e["ranges"]] for e in chosen}
    sel = {"chains": [e["deposit_chain"] for e in chosen], "ranges": ranges}
    omitted = {e["deposit_chain"]: e["omitted"] for e in chosen if e.get("omitted")}
    if omitted:
        sel["omitted_ranges"] = omitted
    if d["effective"]:
        sel["effective_components"] = d["effective"]
    sel["numbering"] = NUMBERING
    sel["build_missing"] = {e["deposit_chain"]: len(tb._validated_build_sites(e))
                            for e in chosen if tb._validated_build_sites(e)}
    sel["differences_from_deposit"] = [x for e in chosen for x in (e.get("differences") or [])]
    sel["modified_residues_reverted"] = d["modres"]
    sel["stated_protonation"] = d["protonation"]
    if disulfides:
        sel["stated_disulfides"] = disulfides
    sel["numbering_certain"] = all(bool(e.get("numbering_certain")) for e in chosen)
    sel["derivation"] = DERIVATION
    if d["excluded"]:
        sel["excluded_components"] = d["excluded"]
    if kept:
        sel["kept_components"] = list(kept)
    return sel


