def plan(workdir=WORKDIR):
    """The 30 task slots in dispatch order, with replacements applied in reserve order."""
    data = json.loads((workdir / "selection" / "selected.json").read_text())
    reserves = collections.defaultdict(list)
    for item in data["reserves"]:
        reserves[item["category"]].append(item)
    slots, replaced = [], []
    for category in ORDER:
        for item in [s for s in data["selected"] if s["category"] == category]:
            current = item
            while current["pdb_id"] in NOT_STATABLE:
                if not reserves[category]:
                    raise SystemExit(f"{category}: no reserve left to replace {current['pdb_id']}")
                nxt = reserves[category].pop(0)
                replaced.append({"category": category, "replaced": current["pdb_id"],
                                 "by": nxt["pdb_id"], "reason": NOT_STATABLE[current["pdb_id"]]})
                current = nxt
            slots.append(current)
    out = []
    for i, item in enumerate(slots):
        axis = item["category"]
        number = FIRST_NUMBER + i
        out.append(dict(item, task_id=f"{number:03d}_{DIR_AXIS.get(axis, axis)}_{item['pdb_id'].lower()}",
                        axis=axis))
    return out, replaced


def fetch(item):
    node, accession, pdb = item["node"], item["accession"], item["pdb_id"]
    bundle = BUNDLE_ROOT / f"{node}_{accession}"
    if not (bundle / "provenance.json").exists():
        fetch_reference(accession, str(bundle), node=node)
    from mddatabench.contract_audit import _deposit_path
    _deposit_path(pdb, DATASET / "_deposits")
    vc.deposit_pdb(WORKDIR, pdb)
    return bundle


def build_task(item, sample, draft_root=None):
    node, accession, pdb = item["node"], item["accession"], item["pdb_id"]
    task_id = item["task_id"]
    bundle = BUNDLE_ROOT / f"{node}_{accession}"
    provenance = json.loads((bundle / "provenance.json").read_text())
    proj = project(node, accession)
    meta = proj.get("metadata") or {}
    d = derive(task_id, node, accession, pdb, bundle=bundle)
    if draft_root is None:
        calibration = calibration_for(node, accession, bundle)
    else:
        # Draft: everything but the calibration, written outside the dataset,
        # so the contract audit can run while the windows are still fetched.
        calibration = {"window_ns": WINDOW_NS.get(node, 1.0),
                       "per_check": {"radius_of_gyration_angstrom": {"scored": True}}}
    window_ns = float(calibration["window_ns"])
    extra = OVERRIDES.get(task_id, {})
    kept = extra.get("kept_components", ())
    prompt = prompt_for(task_id, pdb, d, window_ns, kept=kept)
    disulfides = stated_disulfides(prompt, pdb, bundle)
    if disulfides:
        prompt = prompt_for(task_id, pdb, d, window_ns, disulfides=disulfides, kept=kept)
    stab = vc.stability(vc.rmsds(WORKDIR, node, accession))
    info = d["entry"].get("rcsb_entry_info") or {}
    # As in the cast: MDDB's mdcount, which is also what calibrate() pools over.
    # Dynarepo lists three replicas in ``mds`` but leaves mdcount null, so its
    # contracts (025-030 too) carry one replica and calibrate on replica 1.
    replicas = proj.get("mdcount") or 1
    if replicas != len(calibration.get("replicas_used") or [1]) and draft_root is None:
        raise SystemExit(f"{task_id}: {replicas} replicas but calibrated on "
                         f"{calibration.get('replicas_used')}")
    reference = {
        "database": "MDDB", "node": node, "api": NODES[node], "accession": accession,
        "retrieved": RETRIEVED, "license": meta.get("LICENSE"), "pdb_ids": [pdb],
        "replicas": replicas,
        "reference_conditions": {
            "FF": meta.get("FF"), "WAT": meta.get("WAT"), "TEMP": meta.get("TEMP"),
            "TIMESTEP": meta.get("TIMESTEP"), "FRAMESTEP": meta.get("FRAMESTEP"),
            "PROGRAM": meta.get("PROGRAM"), "METHOD": meta.get("METHOD"),
            "ENSEMBLE": meta.get("ENSEMBLE") or "NPT",
            "ENSEMBLE_recorded_by_reference": meta.get("ENSEMBLE"),
            "PRESSURE_BAR": 1,
            "PRESSURE_recorded_by_reference": meta.get("PCOUPLING"),
        },
        "reference_system": {
            **{k: meta.get(k) for k in ("PROTRES", "PROTATS", "DNARES", "RNARES", "LIPIRES",
                                        "SYSTATS", "SOL", "NA", "CL")},
            "structural_metals": d["metals"],
        },
        "selection": selection_block(d, disulfides, kept),
        "deposit": {
            "method": info.get("experimental_method"),
            "modeled_residues": info.get("deposited_modeled_polymer_monomer_count"),
            "unmodeled_residues": info.get("deposited_unmodeled_polymer_monomer_count"),
            "disulfide_bonds": info.get("disulfide_bond_count"),
            "chains": info.get("deposited_polymer_entity_instance_count"),
        },
        "reference_stability": {
            "last_third_rmsd_angstrom": round(stab["last_third_rmsd_angstrom"], 3),
            "drift_angstrom": round(stab["drift_angstrom"], 3),
            "note": STABILITY_NOTE,
        },
        "bundle": {
            "fetch": (f"mddatabench fetch_benchmark_reference --node {node} --accession "
                      f"{accession} --out <bundle>"),
            "sha256": {p.name: sha256(p) for p in sorted(bundle.glob("*"))
                       if p.name != "provenance.json"},
            "policy": "Fetched at scoring time. Never staged into the solver workspace.",
            "topology_file": provenance.get("topology_file"),
        },
        "md_calibration": calibration,
        "production_window_ns": window_ns,
    }
    if not meta.get("LICENSE"):
        reference["license_note"] = NO_LICENCE_NOTE
    reference["bilayer"] = tb.bilayer(meta)
    task = {
        "schema_version": "1.1", "task_id": task_id, "split": "test", "axis": item["axis"],
        "category": "database_derived_md", "primary_score": "database_agreement",
        "evaluation_target": "agent_md_fidelity", "reference": reference,
        "solve_time_network_policy": NETWORK_POLICY,
        "required_outputs": sample["required_outputs"],
        "scoring": scoring_block(sample, calibration),
    }
    out = (Path(draft_root) if draft_root else DATASET) / "tasks" / task_id
    out.mkdir(parents=True, exist_ok=True)
    (out / "task.json").write_text(json.dumps(task, indent=2, ensure_ascii=False) + "\n")
    (out / "prompt.md").write_text(prompt)
    return {"task_id": task_id, "pdb": pdb, "node": node, "accession": accession,
            "ligands": d["ligands"], "excluded": d["excluded"], "metals": d["metals"],
            "hetero_selected": d["hetero_selected"], "in_reference": d["in_reference"],
            "reference_nonpolymer": d["reference_nonpolymer"],
            "chains": d["chains"], "title": d["title"]}


# Per-task inputs the derivation has no source for (a kept component when the
# deposit carries several instances).  Empty for the 30: none needed one.
OVERRIDES: dict = {}


def stated_disulfides(prompt, pdb, bundle):
    """The deposit/reference disulfide difference, in the deposit's numbering.

    Computed with the contract audit's own functions, so the statement is
    exactly the difference the audit would otherwise report: the deposit's
    struct_conn pairs and the reference topology's S-S bonds, both in the
    prompt's construct frame.  As in the cast (016, 087): ``formed`` lists every
    pair the reference bonds, ``reduced`` every deposited pair it does not.
    """
    from mddatabench import contract_audit as ca
    from mddatabench.topology import sulfur_bond_positions
    cif = DATASET / "_deposits" / f"{pdb.upper()}.cif"
    declared = ca._declared(prompt)
    selected = ca._selected_deposit(ca._structure_records(cif), declared)
    positions = ca._deposit_positions(selected, declared)
    inverse = {v: k for k, v in positions.items()}
    deposit_pairs = ca._deposit_disulfide_positions(cif, declared, selected)
    _, topology = ca._reference_backbone_contract(Path(bundle))
    pairs, _, dropped = sulfur_bond_positions(topology)
    if dropped:
        raise SystemExit(f"{pdb}: reference topology has sulfur bonds outside its polymer")
    reference_pairs = {tuple(sorted(pair)) for pair in pairs}
    if reference_pairs == deposit_pairs:
        return None

    def named(pair):
        (c1, n1, i1), (c2, n2, i2) = inverse[pair[0]], inverse[pair[1]]
        if c1 != c2:
            raise SystemExit(f"{pdb}: inter-chain disulfide {pair} cannot be stated")
        return {"chain": c1, "residues": [f"{n1}{i1}", f"{n2}{i2}"]}
    return {"formed": [named(p) for p in sorted(reference_pairs)] if reference_pairs - deposit_pairs
            or deposit_pairs - reference_pairs else [],
            "reduced": [named(p) for p in sorted(deposit_pairs - reference_pairs)]}


