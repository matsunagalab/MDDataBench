"""The held-out test sets, and every parameter that makes each one reproducible.

The selection and build scripts (``scan_mddb_pool.py``, ``verify_candidates.py``,
``select_test_set.py``, ``build_test_tasks.py``) take ``--set NAME``; the default
is ``v6``, so a rerun without it reproduces the v6 test split (tasks 101-130)
exactly as it was built on 2026-10-31.

A test set is single-use (decision of 2026-11-01): once a frozen MDClaw has run
on it and its failures were used to change MDClaw, it becomes development data,
and the next set excludes it. So each set names the splits that are its
development set, the mdclaw commit whose text it excludes, and the ids, split
and dataset version it is built under.

Rules: docs/test-set-selection.md (v6) and docs/test-set-v7-selection.md (v7, and
its membrane supplement v7m, Part 5).
"""

