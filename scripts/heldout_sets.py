SETS = {s.name: s for s in (V6, V7, V7M)}
DEFAULT = "v6"


def get(name: str | None = None) -> HeldOutSet:
    """The named set (default v6); an unknown name is an error, never a fallback."""
    name = name or DEFAULT
    if name not in SETS:
        raise SystemExit(f"unknown held-out set {name!r}; known: {sorted(SETS)}")
    return SETS[name]
