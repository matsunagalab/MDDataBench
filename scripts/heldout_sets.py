@dataclass(frozen=True)
class HeldOutSet:
    """One held-out test set: where it lives, what it excludes, how it is numbered."""

    name: str
    workdir: Path
    split: str                      # the split value in task.json and dataset.json
    first_number: int               # task id of the first slot in dispatch order
    retrieved: str                  # retrieval date recorded in each contract
    rule_doc: str
    # The 98 shipped tasks (train / eval): diversity anchors, size caps, and the
    # "vs 98" columns.
    cast_splits: tuple = ("train", "eval")
    # Earlier test splits that are now development data: excluded by PDB ID and
    # by the sequence rules, like the cast.
    previous_test_splits: tuple = ()
    # Whether those earlier test tasks are also diversity anchors of their axis.
    previous_tests_are_anchors: bool = False
    mdclaw_commit: str = ""
    mdclaw_not_pdb: dict = field(default_factory=lambda: dict(MDCLAW_NOT_PDB))
    mdprepbench_pdbs: tuple = MDPREPBENCH_PDBS
    # (short name, URL) of each MDStudyBench task contract.
    mdstudybench_tasks: tuple = ()
    not_statable: dict = field(default_factory=dict)
    dataset_id: str = ""
    changelog: str = ""
    # Appended once to dataset.json's description (skipped when ``marker`` is in it).
    description_marker: str = ""
    description_addition: str = ""


